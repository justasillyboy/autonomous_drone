"""Render docs/config-reference.md from the config schema.

    uv run python -m uav_core.config_doc [path]   # default: docs/config-reference.md

tests/test_config_doc.py fails when the committed file drifts from the schema, so the
reference cannot go stale (it replaces the legacy "update config.yaml and the README" rule).
"""

from __future__ import annotations

import inspect
import sys
from collections.abc import Sequence
from pathlib import Path
from typing import Any

import annotated_types as at
from pydantic import BaseModel
from pydantic.fields import FieldInfo

from uav_core.config import MissionConfig, RulebookConfig
from uav_core.types import Round

DEFAULT_PATH = Path("docs/config-reference.md")

_HEADER = """\
<!-- GENERATED by `uv run python -m uav_core.config_doc` from uav_core/config.py. Do not edit. -->

# Mission configuration reference

`MissionConfig` is loaded once from YAML at the boundary (launch file or CLI) and passed
explicitly to constructors. Every key is optional; a missing key keeps its default. Unknown
keys and out-of-range values are startup errors (ADR-0002).

```yaml
drop:
  align_pixel_thresh_px: 20
camera:
  f_px: 487.5
```
"""

_BOUNDS = ((at.Gt, "gt", ">"), (at.Ge, "ge", "≥"), (at.Lt, "lt", "<"), (at.Le, "le", "≤"))


def _fmt(value: Any) -> str:
    if isinstance(value, BaseModel):
        return ", ".join(f"{name}={_fmt(v)}" for name, v in value)
    if isinstance(value, dict):
        # The only mapping in the schema: colour -> HSV (lo, hi) ranges.
        return "<br>".join(
            f"{key}: " + " ∪ ".join(f"{_fmt(lo)}–{_fmt(hi)}" for lo, hi in ranges)
            for key, ranges in value.items()
        )
    if isinstance(value, tuple):
        return "(" + ", ".join(_fmt(v) for v in value) + ")"
    if isinstance(value, float):
        return f"{value:g}"
    return str(value)


def _constraints(info: FieldInfo) -> str:
    parts = []
    for meta in info.metadata:
        for kind, attr, symbol in _BOUNDS:
            if isinstance(meta, kind):
                parts.append(f"{symbol} {_fmt(getattr(meta, attr))}")
        if isinstance(meta, at.MinLen):
            parts.append(f"length ≥ {meta.min_length}")
    return ", ".join(parts) or "–"


def _cell(text: str) -> str:
    return text.replace("|", r"\|")


def _section(name: str, model: type[BaseModel]) -> list[str]:
    lines = [f"## `{name}`", ""]
    doc = model.__dict__.get("__doc__")
    if doc:
        lines += [inspect.cleandoc(doc), ""]
    lines += [
        "| Key | Default | Unit | Constraints | Description | Source |",
        "|---|---|---|---|---|---|",
    ]
    for field, info in model.model_fields.items():
        extra = info.json_schema_extra or {}
        cells = (
            f"`{name}.{field}`",
            _fmt(info.get_default(call_default_factory=True)),
            str(extra.get("unit", "–")),
            _constraints(info),
            info.description or "",
            str(extra.get("source", "")),
        )
        lines.append("| " + " | ".join(_cell(c) for c in cells) + " |")
    return [*lines, ""]


def _rulebook() -> list[str]:
    rules = RulebookConfig()
    lines = [
        "## Rulebook constants (read-only)",
        "",
        "`RulebookConfig` is not loaded from YAML: it changes only if the rules change.",
        "",
        "| Name | Value |",
        "|---|---|",
    ]
    lines += [
        f"| `{name}` | {_fmt(value)} |" for name, value in rules if not isinstance(value, tuple)
    ]
    for round_ in Round:
        lines += [
            "",
            f"### Fire targets, {round_.value} (in flight order)",
            "",
            "| Label | Colour | Points | Diameter (m) | Moving |",
            "|---|---|---|---|---|",
        ]
        lines += [
            f"| {t.label} | {t.color.value} | {t.points} | {_fmt(t.diameter_m)} | "
            f"{'yes' if t.moving else 'no'} |"
            for t in rules.targets(round_)
        ]
    return [*lines, ""]


def render_markdown() -> str:
    lines = [_HEADER]
    for name, info in MissionConfig.model_fields.items():
        lines += _section(name, info.annotation)
    lines += _rulebook()
    return "\n".join(lines).rstrip("\n") + "\n"


def main(argv: Sequence[str] | None = None) -> int:
    args = list(sys.argv[1:] if argv is None else argv)
    path = Path(args[0]) if args else DEFAULT_PATH
    path.write_text(render_markdown())
    print(f"wrote {path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
